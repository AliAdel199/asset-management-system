// =============================================================================
// إعداد PM2: تشغيل النظام في وضع الإنتاج
// =============================================================================
//
// PM2 مدير عمليات يشغّل الخادم الخلفي والواجهة في الخلفية،
// ويعيد تشغيل أي منهما تلقائيًا إذا تعطّل، ويحفظ السجلات في مجلد logs/.
//
// يشغّل هذا الملف النسخة المبنية مسبقًا (build)، وليس الكود المصدري مباشرة.
// لذلك أي تعديل على الكود لن يظهر حتى تعيد البناء:
//     scripts\deploy-prod.cmd
//
// أوامر مفيدة:
//     pm2 ls              حالة التطبيقات
//     pm2 logs            السجلات مباشرة
//     pm2 restart all     إعادة التشغيل
//
// إذا عدّلت هذا الملف نفسه، طبّق التعديل بـ:
//     pm2 delete all && pm2 start ecosystem.config.cjs && pm2 save
// =============================================================================

const path = require('path');

// مجلد جذر المشروع (المجلد الذي يحتوي هذا الملف).
// نحوّل حرف القرص إلى حرف كبير (d:\ إلى D:\) لأن Next.js على Windows
// يرجع 404 لكل الصفحات إذا اختلف حرف القرص عن المسار الحقيقي.
const root = __dirname.replace(/^[a-z]:/, (d) => d.toUpperCase());

// مسار مختصر لأي ملف داخل المشروع.
const p = (...parts) => path.join(root, ...parts);

// إعدادات مشتركة بين التطبيقين.
const common = {
  // يعيد التشغيل تلقائيًا إذا توقفت العملية بشكل غير متوقع.
  autorestart: true,
  // حد أقصى لمحاولات إعادة التشغيل المتتالية، حتى لا يدخل في حلقة لا نهائية
  // إذا كان الخطأ دائمًا (مثل قاعدة بيانات متوقفة).
  max_restarts: 10,
  // ينتظر 5 ثوانٍ بين كل محاولة إعادة تشغيل.
  restart_delay: 5000,
  // يضيف التاريخ والوقت أمام كل سطر في السجلات.
  time: true,
};

module.exports = {
  apps: [
    // -------------------------------------------------------------------------
    // الخادم الخلفي (NestJS) على المنفذ 3001
    // -------------------------------------------------------------------------
    {
      ...common,
      name: 'ams-api',
      // مجلد العمل مهم لأمرين:
      //   - dotenv يقرأ ملف .env من هذا المجلد (رابط قاعدة البيانات، JWT_SECRET...)
      //   - المرفقات المرفوعة تُحفظ في apps/api/uploads
      cwd: p('apps/api'),
      // ناتج "nest build". المسار dist/src/main.js وليس dist/main.js
      // لأن tsconfig يضم مجلدات أخرى غير src.
      script: p('apps/api/dist/src/main.js'),
      env: {
        NODE_ENV: 'production',
        PORT: '3001',
      },
      out_file: p('logs/api.out.log'),
      error_file: p('logs/api.err.log'),
    },

    // -------------------------------------------------------------------------
    // الواجهة (Next.js) على المنفذ 3000، وهي نقطة الدخول من الشبكة
    // -------------------------------------------------------------------------
    {
      ...common,
      name: 'ams-web',
      cwd: p('apps/web'),
      // نشغّل ملف next عبر node مباشرة لأن PM2 على Windows
      // لا يشغّل npm.cmd أو next.cmd بشكل موثوق.
      script: p('node_modules/next/dist/bin/next'),
      // start يشغّل نسخة الإنتاج المبنية في apps/web/.next
      // -H 0.0.0.0  يستقبل الاتصالات من كل الشبكات، وليس من هذا الجهاز فقط
      // -p 3000     المنفذ
      args: 'start -H 0.0.0.0 -p 3000',
      env: {
        NODE_ENV: 'production',
      },
      out_file: p('logs/web.out.log'),
      error_file: p('logs/web.err.log'),
    },
  ],
};
