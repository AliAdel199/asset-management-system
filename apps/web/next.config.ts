import type { NextConfig } from "next";

// =============================================================================
// إعداد Next.js للواجهة
// =============================================================================
//
// الفكرة: الواجهة (المنفذ 3000) هي نقطة الدخول الوحيدة للنظام من الشبكة.
// أي طلب يبدأ بـ /api أو /uploads يُمرَّر داخليًا إلى الخادم الخلفي (المنفذ 3001)
// على نفس الجهاز، فالمتصفح لا يحتاج أن يعرف عنوان الخادم الخلفي أبدًا.
//
// الفائدة:
//   1. الجهاز الآخر على الشبكة يحتاج عنوانًا واحدًا فقط: http://<IP>:3000
//   2. لا مشاكل CORS، لأن المتصفح يرى كل الطلبات من نفس الأصل (origin).
//   3. إذا تغيّر IP الجهاز لا نحتاج إعادة بناء الواجهة.
//   4. نفتح منفذًا واحدًا فقط في الجدار الناري (3000) بدل منفذين.
//
// ملاحظة: هذا التمرير يعمل فقط عندما تستدعي الواجهة مسارات نسبية (/api/...).
// لذلك نضبط NEXT_PUBLIC_API_BASE_URL="/api" عند بناء الإنتاج
// (انظر apps/web/.env.production.local).

// عنوان الخادم الخلفي كما تراه عملية Next.js نفسها (وليس المتصفح).
// 127.0.0.1 لأن الاثنين يعملان على نفس الجهاز. يمكن تغييره عبر متغير البيئة
// API_PROXY_TARGET إذا نُقل الخادم الخلفي إلى جهاز آخر.
const apiProxyTarget = process.env.API_PROXY_TARGET ?? "http://127.0.0.1:3001";

const nextConfig: NextConfig = {
  experimental: {
    // أقصى حجم لجسم الطلب الذي يمرّره Next.js إلى الخادم الخلفي.
    // القيمة الافتراضية 10MB، وأي طلب أكبر يُقطع فيفشل رفع المرفق بخطأ 500.
    // الخادم الخلفي يقبل مرفقات حتى 25MB (apps/api/src/assets/attachment-storage.ts)،
    // فنضبطها على 30MB لتغطي حجم الملف مع غلاف طلب الرفع (multipart).
    // إذا رفعت حد الخادم الخلفي، ارفع هذه القيمة معه.
    proxyClientMaxBodySize: "30mb",
  },

  async rewrites() {
    return [
      {
        // كل استدعاءات الـ API، مثل /api/auth/login و /api/assets
        source: "/api/:path*",
        destination: `${apiProxyTarget}/api/:path*`,
      },
      {
        // المرفقات المرفوعة (صور ومستندات) يخدمها الخادم الخلفي من مجلد uploads
        source: "/uploads/:path*",
        destination: `${apiProxyTarget}/uploads/:path*`,
      },
    ];
  },
};

export default nextConfig;
